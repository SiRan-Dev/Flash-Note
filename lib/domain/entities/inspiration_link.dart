import 'package:freezed_annotation/freezed_annotation.dart';

part 'inspiration_link.freezed.dart';
part 'inspiration_link.g.dart';

enum LinkType { similar, causal, complementary, opposite, parentChild }

@freezed
class InspirationLink with _$InspirationLink {
  const factory InspirationLink({
    required int id,
    required int sourceId,
    required int targetId,
    required LinkType linkType,
    String? relationLabel,
    @Default(0.5) double confidence,
    @Default(false) bool isAutoGenerated,
    required DateTime createdAt,
  }) = _InspirationLink;

  factory InspirationLink.fromJson(Map<String, dynamic> json) =>
      _$InspirationLinkFromJson(json);
}
