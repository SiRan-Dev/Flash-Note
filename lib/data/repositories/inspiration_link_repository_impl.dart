import 'package:drift/drift.dart';
import 'package:flashnote/data/datasources/local/app_database.dart' as db;
import 'package:flashnote/domain/entities/inspiration_link.dart' as domain;
import 'package:flashnote/domain/repositories/inspiration_link_repository.dart';

class InspirationLinkRepositoryImpl implements InspirationLinkRepository {
  final db.AppDatabase _db;

  InspirationLinkRepositoryImpl(this._db);

  String _linkTypeToString(domain.LinkType type) {
    switch (type) {
      case domain.LinkType.similar:
        return 'similar';
      case domain.LinkType.causal:
        return 'causal';
      case domain.LinkType.complementary:
        return 'complementary';
      case domain.LinkType.opposite:
        return 'opposite';
      case domain.LinkType.parentChild:
        return 'parentChild';
    }
  }

  domain.LinkType _linkTypeFromString(String value) {
    switch (value) {
      case 'similar':
        return domain.LinkType.similar;
      case 'causal':
        return domain.LinkType.causal;
      case 'complementary':
        return domain.LinkType.complementary;
      case 'opposite':
        return domain.LinkType.opposite;
      case 'parentChild':
      case 'parent_child':
        return domain.LinkType.parentChild;
      default:
        return domain.LinkType.similar;
    }
  }

  domain.InspirationLink _fromRow(db.InspirationLink row) {
    return domain.InspirationLink(
      id: row.id,
      sourceId: row.sourceId,
      targetId: row.targetId,
      linkType: _linkTypeFromString(row.linkType),
      relationLabel: row.relationLabel,
      confidence: row.confidence,
      isAutoGenerated: row.isAutoGenerated,
      createdAt: DateTime.fromMillisecondsSinceEpoch(row.createdAt),
    );
  }

  @override
  Future<List<domain.InspirationLink>> getLinksForInspiration(
    int inspirationId,
  ) async {
    final rows = await _db.getLinksForInspiration(inspirationId);
    return rows.map(_fromRow).toList();
  }

  @override
  Future<List<domain.InspirationLink>> getLinksBySourceId(int sourceId) async {
    final rows = await _db.getLinksBySourceId(sourceId);
    return rows.map(_fromRow).toList();
  }

  @override
  Future<List<domain.InspirationLink>> getLinksByTargetId(int targetId) async {
    final rows = await _db.getLinksByTargetId(targetId);
    return rows.map(_fromRow).toList();
  }

  @override
  Future<domain.InspirationLink?> getById(int id) async {
    final row = await _db.getLinkById(id);
    return row != null ? _fromRow(row) : null;
  }

  @override
  Future<domain.InspirationLink?> getParentLink(int childId) async {
    final links = await getLinksByTargetId(childId);
    for (final link in links) {
      if (link.linkType == domain.LinkType.parentChild) {
        return link;
      }
    }
    return null;
  }

  @override
  Future<domain.InspirationLink?> getLinkBetween(
    int sourceId,
    int targetId, {
    domain.LinkType? linkType,
    bool directed = false,
  }) async {
    final rows = await _db.getAllInspirationLinks();
    for (final row in rows) {
      final typeMatches =
          linkType == null || row.linkType == _linkTypeToString(linkType);
      final directionMatches =
          directed
              ? row.sourceId == sourceId && row.targetId == targetId
              : (row.sourceId == sourceId && row.targetId == targetId) ||
                  (row.sourceId == targetId && row.targetId == sourceId);
      if (typeMatches && directionMatches) return _fromRow(row);
    }
    return null;
  }

  @override
  Future<int> create(domain.InspirationLink link) {
    final entry = db.InspirationLinksCompanion.insert(
      sourceId: link.sourceId,
      targetId: link.targetId,
      linkType: _linkTypeToString(link.linkType),
      relationLabel: Value(link.relationLabel),
      confidence: Value(link.confidence),
      isAutoGenerated: Value(link.isAutoGenerated),
      createdAt: link.createdAt.millisecondsSinceEpoch,
    );
    return _db.insertInspirationLink(entry);
  }

  @override
  Future<int> restore(domain.InspirationLink link) {
    final entry = db.InspirationLinksCompanion.insert(
      id: Value(link.id),
      sourceId: link.sourceId,
      targetId: link.targetId,
      linkType: _linkTypeToString(link.linkType),
      relationLabel: Value(link.relationLabel),
      confidence: Value(link.confidence),
      isAutoGenerated: Value(link.isAutoGenerated),
      createdAt: link.createdAt.millisecondsSinceEpoch,
    );
    return _db.insertInspirationLink(entry);
  }

  @override
  Future<int> updateRelationLabel(int id, String? relationLabel) {
    return _db.updateInspirationLink(
      id,
      db.InspirationLinksCompanion(relationLabel: Value(relationLabel)),
    );
  }

  @override
  Future<int> delete(int id) async {
    await _db.markRecordDeleted('inspirationLinks', id);
    return _db.deleteInspirationLink(id);
  }

  @override
  Future<int> deleteParentChild(int parentId, int childId) async {
    final link = await getLinkBetween(
      parentId,
      childId,
      linkType: domain.LinkType.parentChild,
      directed: true,
    );
    if (link == null) return 0;
    return delete(link.id);
  }

  @override
  Future<int> deleteForInspiration(int inspirationId) async {
    final links = await _db.getLinksForInspiration(inspirationId);
    for (final link in links) {
      await _db.markRecordDeleted('inspirationLinks', link.id);
    }
    return _db.deleteLinksForInspiration(inspirationId);
  }

  @override
  Future<bool> exists(
    int sourceId,
    int targetId, {
    domain.LinkType? linkType,
    bool directed = false,
  }) async {
    if (linkType == null && !directed) {
      return _db.linkExists(sourceId, targetId);
    }
    final link = await getLinkBetween(
      sourceId,
      targetId,
      linkType: linkType,
      directed: directed,
    );
    return link != null;
  }

  @override
  Future<bool> wouldCreateParentChildCycle(int parentId, int childId) async {
    if (parentId == childId) return true;

    final rows = await _db.getAllInspirationLinks();
    final childrenByParent = <int, List<int>>{};
    for (final row in rows) {
      if (row.linkType != 'parentChild' && row.linkType != 'parent_child') {
        continue;
      }
      childrenByParent.putIfAbsent(row.sourceId, () => []).add(row.targetId);
    }

    final visited = <int>{};
    final stack = <int>[childId];
    while (stack.isNotEmpty) {
      final current = stack.removeLast();
      if (!visited.add(current)) continue;
      if (current == parentId) return true;
      stack.addAll(childrenByParent[current] ?? const <int>[]);
    }
    return false;
  }
}
