import 'package:drift/drift.dart';
import 'package:flashnote/data/datasources/local/entity_uuids.dart';

@TableIndex(
  name: 'inspiration_links_uuid_unique',
  columns: {#uuid},
  unique: true,
)
class InspirationLinks extends Table {
  IntColumn get id => integer().autoIncrement()();
  IntColumn get sourceId => integer()();
  IntColumn get targetId => integer()();
  TextColumn get linkType =>
      text().withLength(
        min: 1,
      )(); // similar/causal/complementary/opposite/parentChild
  TextColumn get relationLabel => text().nullable()();
  RealColumn get confidence => real().withDefault(const Constant(0.5))();
  BoolColumn get isAutoGenerated =>
      boolean().withDefault(const Constant(false))();
  IntColumn get createdAt => integer()();

  /// 跨设备唯一身份，[id] 保持不变。
  TextColumn get uuid =>
      text().clientDefault(newUuidV4).customConstraint("NOT NULL DEFAULT ''")();
}
