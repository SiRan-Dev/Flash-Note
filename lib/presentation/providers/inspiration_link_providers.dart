import 'package:flashnote/domain/repositories/inspiration_link_repository.dart';
import 'package:flashnote/presentation/providers/ai_providers.dart';
import 'package:flashnote/presentation/providers/database_provider.dart';
import 'package:flashnote/presentation/providers/inspiration_providers.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

// === Repositories ===

final inspirationLinkRepositoryProvider =
    Provider<InspirationLinkRepository>((ref) {
  return InspirationLinkRepositoryImpl(ref.watch(databaseProvider));
});

final clusterRepositoryProvider = Provider<ClusterRepository>((ref) {
  return ClusterRepositoryImpl(ref.watch(databaseProvider));
});

// === Inspiration Links ===

/// 获取灵感的所有关联
final inspirationLinksProvider =
    FutureProvider.family<List<InspirationLink>, int>((ref, inspirationId) {
  final repo = ref.watch(inspirationLinkRepositoryProvider);
  return repo.getLinksForInspiration(inspirationId);
});

// === Clusters ===

/// 所有分组列表
final clusterListProvider = FutureProvider<List<Cluster>>((ref) {
  final repo = ref.watch(clusterRepositoryProvider);
  return repo.getAll();
});

/// 自动发现关联（调用 AI）
final autoDiscoverLinksProvider =
    FutureProvider.family<List<InspirationLink>, int>(
        (ref, inspirationId) async {
  final aiReady = await ref.watch(aiConfigReadyProvider.future);
  if (!aiReady) return [];

  final inspirationRepo = ref.watch(inspirationRepositoryProvider);
  final linkRepo = ref.watch(inspirationLinkRepositoryProvider);
  final aiService = ref.watch(aiServiceProvider);
  final preset = await ref.watch(selectedPresetProvider.future);
  final apiKey = await ref.watch(currentApiKeyProvider.future);

  if (preset == null || apiKey == null) return [];

  final target = await inspirationRepo.getById(inspirationId);
  if (target == null) return [];

  final allInspirations = await inspirationRepo.getAll();
  final candidates = allInspirations
      .where((i) => i.id != inspirationId)
      .map((i) => (i.id, i.content))
      .toList();

  if (candidates.isEmpty) return [];

  final discovered = await aiService.findRelationships(
    inspirationId,
    target.content,
    candidates,
    preset,
    apiKey,
  );

  // 保存新发现的关联
  for (final link in discovered) {
    final exists = await linkRepo.exists(link.sourceId, link.targetId);
    if (!exists) {
      await linkRepo.create(InspirationLink(
        id: 0,
        sourceId: link.sourceId,
        targetId: link.targetId,
        linkType: link.linkType,
        confidence: link.confidence,
        isAutoGenerated: true,
        createdAt: DateTime.now(),
      ));
    }
  }

  return linkRepo.getLinksForInspiration(inspirationId);
});
