import 'dart:io';

import 'package:drift/native.dart';
import 'package:flashnote/data/datasources/local/ai_settings_storage.dart';
import 'package:flashnote/data/datasources/local/app_database.dart';
import 'package:flashnote/data/datasources/local/entity_uuids.dart';
import 'package:flashnote/data/datasources/local/webdav_storage.dart';
import 'package:flashnote/data/services/webdav_sync_service.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  Map<String, dynamic> snapshot({
    String deviceId = 'device-a',
    List<Map<String, dynamic>> inspirations = const [],
    List<Map<String, dynamic>> inspirationLinks = const [],
    List<Map<String, dynamic>> deletedRecords = const [],
  }) {
    return {
      'version': 7,
      'deviceId': deviceId,
      'exportedAt': '2026-05-16T00:00:00.000',
      'inspirations': inspirations,
      'projects': <Map<String, dynamic>>[],
      'tasks': <Map<String, dynamic>>[],
      'customSources': <Map<String, dynamic>>[],
      'attachments': <Map<String, dynamic>>[],
      'chatMessages': <Map<String, dynamic>>[],
      'inspirationLinks': inspirationLinks,
      'clusters': <Map<String, dynamic>>[],
      'deletedRecords': deletedRecords,
      'aiSettings': <String, dynamic>{},
    };
  }

  Map<String, dynamic> legacyInspiration({
    required int legacyId,
    required String content,
    required int createdAt,
    required int updatedAt,
  }) {
    return {
      'uuid': legacyRecordUuid('inspirations', legacyId, createdAt),
      'legacyId': legacyId,
      'content': content,
      'createdAt': createdAt,
      'updatedAt': updatedAt,
      'isPinned': false,
    };
  }

  group('WebDavSyncService merge', () {
    test('旧墓碑（legacyId）会阻止远端旧灵感恢复', () {
      final merged = WebDavSyncService.mergeSnapshotsForTesting(
        snapshot(
          deletedRecords: [
            {
              'entityType': 'inspirations',
              'entityUuid': legacyTombstoneUuid('inspirations', 1),
              'deletedAt': 2000,
              'legacy': true,
              'entityId': 1,
            },
          ],
        ),
        snapshot(
          inspirations: [
            legacyInspiration(
              legacyId: 1,
              content: '远端旧灵感',
              createdAt: 1000,
              updatedAt: 1500,
            ),
          ],
        ),
      );

      expect(merged['inspirations'], isEmpty);
      expect(merged['deletedRecords'], [
        {
          'entityType': 'inspirations',
          'entityUuid': legacyTombstoneUuid('inspirations', 1),
          'deletedAt': 2000,
          'legacy': true,
          'entityId': 1,
        },
      ]);
    });

    test('删除墓碑不会过滤删除后重新更新的记录', () {
      final merged = WebDavSyncService.mergeSnapshotsForTesting(
        snapshot(
          deletedRecords: [
            {
              'entityType': 'inspirations',
              'entityUuid': legacyTombstoneUuid('inspirations', 1),
              'deletedAt': 2000,
              'legacy': true,
              'entityId': 1,
            },
          ],
        ),
        snapshot(
          inspirations: [
            legacyInspiration(
              legacyId: 1,
              content: '删除后更新的远端灵感',
              createdAt: 1000,
              updatedAt: 3000,
            ),
          ],
        ),
      );

      final inspirations = (merged['inspirations'] as List)
          .cast<Map<String, dynamic>>();
      expect(inspirations, hasLength(1));
      expect(inspirations.single['content'], '删除后更新的远端灵感');
    });

    test('无 updatedAt 的关系记录使用 createdAt 与删除墓碑比较', () {
      final sourceUuid = legacyRecordUuid('inspirations', 1, 1000);
      final targetUuid = legacyRecordUuid('inspirations', 2, 1000);
      final merged = WebDavSyncService.mergeSnapshotsForTesting(
        snapshot(
          deletedRecords: [
            {
              'entityType': 'inspirationLinks',
              'entityUuid': legacyTombstoneUuid('inspirationLinks', 10),
              'deletedAt': 2000,
              'legacy': true,
              'entityId': 10,
            },
          ],
        ),
        snapshot(
          inspirations: [
            legacyInspiration(
              legacyId: 1,
              content: 'A',
              createdAt: 1000,
              updatedAt: 1000,
            ),
            legacyInspiration(
              legacyId: 2,
              content: 'B',
              createdAt: 1000,
              updatedAt: 1000,
            ),
          ],
          inspirationLinks: [
            {
              'uuid': legacyRecordUuid('inspirationLinks', 10, 1500),
              'legacyId': 10,
              'sourceUuid': sourceUuid,
              'targetUuid': targetUuid,
              'linkType': 'similar',
              'confidence': 0.8,
              'isAutoGenerated': false,
              'createdAt': 1500,
            },
          ],
        ),
      );

      expect(merged['inspirationLinks'], isEmpty);
      expect(merged['inspirations'] as List, hasLength(2));
    });

    test('同一 uuid 的删除墓碑合并时保留最新 deletedAt', () {
      final tombstoneUuid = legacyTombstoneUuid('tasks', 7);
      final merged = WebDavSyncService.mergeSnapshotsForTesting(
        snapshot(
          deletedRecords: [
            {
              'entityType': 'tasks',
              'entityUuid': tombstoneUuid,
              'deletedAt': 2000,
              'legacy': true,
              'entityId': 7,
            },
          ],
        ),
        snapshot(
          deviceId: 'device-b',
          deletedRecords: [
            {
              'entityType': 'tasks',
              'entityUuid': tombstoneUuid,
              'deletedAt': 3000,
              'legacy': true,
              'entityId': 7,
            },
          ],
        ),
      );

      expect(merged['deletedRecords'], [
        {
          'entityType': 'tasks',
          'entityUuid': tombstoneUuid,
          'deletedAt': 3000,
          'legacy': true,
          'entityId': 7,
        },
      ]);
    });
  });

  group('WebDavSyncService reports merge', () {
    Map<String, dynamic> snapshotWithReports(
      List<Map<String, dynamic>> reports,
    ) {
      return {
        'version': 7,
        'deviceId': 'device-a',
        'exportedAt': '2026-05-16T00:00:00.000',
        'inspirations': <Map<String, dynamic>>[],
        'projects': <Map<String, dynamic>>[],
        'tasks': <Map<String, dynamic>>[],
        'customSources': <Map<String, dynamic>>[],
        'attachments': <Map<String, dynamic>>[],
        'chatMessages': <Map<String, dynamic>>[],
        'inspirationLinks': <Map<String, dynamic>>[],
        'clusters': <Map<String, dynamic>>[],
        'deletedRecords': <Map<String, dynamic>>[],
        'reports': reports,
        'aiSettings': <String, dynamic>{},
      };
    }

    test('周报/月报/洞察纳入合并，不会被清空', () {
      final merged = WebDavSyncService.mergeSnapshotsForTesting(
        snapshotWithReports([
          {
            'uuid': deterministicReportUuid('weekly'),
            'type': 'weekly',
            'content': '本地周报',
            'model': 'm',
            'createdAt': 1000,
            'updatedAt': 2000,
          },
        ]),
        snapshotWithReports([
          {
            'uuid': deterministicReportUuid('monthly'),
            'type': 'monthly',
            'content': '远端月报',
            'model': 'm',
            'createdAt': 1500,
            'updatedAt': 2500,
          },
        ]),
      );

      final reports = (merged['reports'] as List).cast<Map<String, dynamic>>();
      expect(reports, hasLength(2));
      expect(reports.map((r) => r['type']), containsAll(['weekly', 'monthly']));
    });
  });

  group('WebDavSyncService credential stripping', () {
    test('上传快照不包含 API Key 与 WebDAV 密码', () {
      final stripped = WebDavSyncService.stripCredentialsForTesting({
        'version': 6,
        'aiSettings': {
          'interfaces': {
            'openai_compatible': {
              'baseUrl': 'https://api.example.com/v1',
              'model': 'gpt',
              'apiKey': 'sk-secret',
            },
          },
          'apiKeys': {'legacy': 'sk-legacy'},
        },
        'webdavSettings': {
          'serverUrl': 'https://dav.example.com',
          'username': 'user',
          'password': 'dav-secret',
        },
      });

      final aiSettings = stripped['aiSettings'] as Map<String, dynamic>;
      expect(aiSettings.containsKey('apiKeys'), isFalse);
      final interfaces = aiSettings['interfaces'] as Map<String, dynamic>;
      final openAi = interfaces['openai_compatible'] as Map<String, dynamic>;
      expect(openAi.containsKey('apiKey'), isFalse);
      expect(openAi['baseUrl'], 'https://api.example.com/v1');

      final webdavSettings = stripped['webdavSettings'] as Map<String, dynamic>;
      expect(webdavSettings.containsKey('password'), isFalse);
      expect(webdavSettings['username'], 'user');
    });
  });

  group('WebDavSyncService import safety', () {
    late AppDatabase db;
    late WebDavSyncService service;

    Map<String, dynamic> emptySnapshot({
      List<Map<String, dynamic>> inspirations = const [],
    }) {
      return {
        'version': 6,
        'exportedAt': '2026-05-16T00:00:00.000',
        'inspirations': inspirations,
        'projects': <Map<String, dynamic>>[],
        'tasks': <Map<String, dynamic>>[],
        'customSources': <Map<String, dynamic>>[],
        'attachments': <Map<String, dynamic>>[],
        'chatMessages': <Map<String, dynamic>>[],
        'inspirationLinks': <Map<String, dynamic>>[],
        'clusters': <Map<String, dynamic>>[],
        'deletedRecords': <Map<String, dynamic>>[],
        'reports': <Map<String, dynamic>>[],
      };
    }

    setUp(() async {
      db = AppDatabase.forTesting(NativeDatabase.memory());
      SharedPreferences.setMockInitialValues({});
      final prefs = await SharedPreferences.getInstance();
      service = WebDavSyncService(
        db: db,
        aiStorage: AiSettingsStorage(prefs: prefs),
        webdavStorage: WebDavStorage(prefs: prefs),
      );
      await db.insertInspiration(
        InspirationsCompanion.insert(
          content: '本地已有灵感',
          createdAt: 1000,
          updatedAt: 1000,
        ),
      );
    });

    tearDown(() async {
      await db.close();
    });

    test('快照校验失败时本地数据保持不变', () async {
      final invalid = emptySnapshot(
        inspirations: [
          // 缺少必填的 content 字段
          {'id': 1, 'createdAt': 1, 'updatedAt': 1, 'isPinned': false},
        ],
      );

      await expectLater(
        service.importSnapshotForTesting(invalid),
        throwsFormatException,
      );

      final rows = await db.getAllInspirations();
      expect(rows, hasLength(1));
      expect(rows.single.content, '本地已有灵感');
    });

    test('写库失败时事务回滚，本地数据保持不变', () async {
      const duplicateUuid = '00000000-0000-4000-8000-000000000001';
      final duplicateUuids = {
        ...emptySnapshot(),
        'version': 7,
        'deviceId': 'device-test',
        'inspirations': [
          {
            'uuid': duplicateUuid,
            'content': 'A',
            'createdAt': 1,
            'updatedAt': 1,
            'isPinned': false,
          },
          {
            'uuid': duplicateUuid,
            'content': 'B',
            'createdAt': 2,
            'updatedAt': 2,
            'isPinned': false,
          },
        ],
      };

      await expectLater(
        service.importSnapshotForTesting(duplicateUuids),
        throwsFormatException,
      );

      final rows = await db.getAllInspirations();
      expect(rows, hasLength(1));
      expect(rows.single.content, '本地已有灵感');
    });

    test('导入不会删除本地附件文件', () async {
      final tempDir = await Directory.systemTemp.createTemp('flashnote_test');
      final attachmentFile = File('${tempDir.path}/note.txt');
      await attachmentFile.writeAsString('附件内容');
      await db.insertAttachment(
        AttachmentsCompanion.insert(
          ownerType: 'inspiration',
          ownerId: 1,
          fileName: 'note.txt',
          filePath: attachmentFile.path,
          mimeType: 'text/plain',
          createdAt: 1000,
        ),
      );

      await service.importSnapshotForTesting(emptySnapshot());

      expect(await attachmentFile.exists(), isTrue);
      await tempDir.delete(recursive: true);
    });
  });
}
